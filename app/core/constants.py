def wuxing_relation(me: str, other: str) -> str:
    """以 me 为「我」，返回 other 相对我的关系：生我/我生/克我/我克/同我。"""
    if me == other:
        return "同我"
    if SHENG[other] == me:
        return "生我"
    if SHENG[me] == other:
        return "我生"
    if KE[other] == me:
        return "克我"
    if KE[me] == other:
        return "我克"
    raise ValueError(f"未知五行关系: {me} / {other}")


